import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";
import { useRef } from "react";
import { toast } from "react-hot-toast";
import axiosInstance from "@/services/api-client";
import { ApiError, ApiSuccess } from "@/types/apiResponse.types";
import axios from "axios";

const TOAST_ID = "cec-tracker-action";

const toApiError = (error: unknown): ApiError => {
  if (axios.isAxiosError(error) && error.response?.data) {
    return error.response.data as ApiError;
  }
  return {
    success: false,
    message: error instanceof Error ? error.message : "Unexpected error",
    data: null,
    statusCode: 500,
  };
};

export function useCecTracker<T extends Record<string, any>>(apiBase: string, queryKey: string, defaultStats: T) {
  const rowsQuery = useQuery({
    queryKey: [queryKey, "rows"],
    queryFn: async () => {
      const res = await axiosInstance.get(`${apiBase}/clients-with-logs`, { params: { limit: 200 } });
      return (res.data?.data?.rows ?? []) as Record<string, any>[];
    },
    staleTime: 30_000,
  });

  const statsQuery = useQuery({
    queryKey: [queryKey, "stats"],
    queryFn: async () => {
      const res = await axiosInstance.get(`${apiBase}/stats`);
      return (res.data?.data ?? defaultStats) as T;
    },
    staleTime: 30_000,
  });

  return {
    data: rowsQuery.data ?? [],
    stats: statsQuery.data ?? defaultStats,
    isLoading: rowsQuery.isLoading || statsQuery.isLoading,
    refetch: () => { void rowsQuery.refetch(); void statsQuery.refetch(); },
  };
}

export function useCecMutations(apiBase: string, queryKey: string) {
  const queryClient = useQueryClient();

  const invalidate = () => {
    void queryClient.invalidateQueries({ queryKey: [queryKey] });
  };

  const createRow = useMutation<ApiSuccess<any>, ApiError, Record<string, any>>({
    mutationKey: [`${queryKey}-create`],
    mutationFn: async (body) => {
      try {
        const res = await axiosInstance.post<ApiSuccess<any>>(apiBase, body);
        return res.data;
      } catch (err) {
        throw toApiError(err);
      }
    },
    onMutate: () => {
      toast.loading("Saving...", { id: TOAST_ID });
    },
    onSuccess: () => {
      toast.success("Saved", { id: TOAST_ID });
      invalidate();
    },
    onError: (err) => {
      toast.error(err.message || "Failed to save", { id: TOAST_ID });
    },
  });

  const updateRow = useMutation<ApiSuccess<any>, ApiError, { id: string; fields: Record<string, any> }>({
    mutationKey: [`${queryKey}-update`],
    mutationFn: async ({ id, fields }) => {
      try {
        const res = await axiosInstance.put<ApiSuccess<any>>(`${apiBase}/${id}`, fields);
        return res.data;
      } catch (err) {
        throw toApiError(err);
      }
    },
    onMutate: () => {
      toast.loading("Saving...", { id: TOAST_ID });
    },
    onSuccess: () => {
      toast.success("Saved", { id: TOAST_ID });
      invalidate();
    },
    onError: (err) => {
      toast.error(err.message || "Failed to save", { id: TOAST_ID });
    },
  });

  const deleteRow = useMutation<ApiSuccess<any>, ApiError, { id: string }>({
    mutationKey: [`${queryKey}-delete`],
    mutationFn: async ({ id }) => {
      try {
        const res = await axiosInstance.delete<ApiSuccess<any>>(`${apiBase}/${id}`);
        return res.data;
      } catch (err) {
        throw toApiError(err);
      }
    },
    onMutate: () => {
      toast.loading("Deleting...", { id: TOAST_ID });
    },
    onSuccess: () => {
      toast.success("Deleted", { id: TOAST_ID });
      invalidate();
    },
    onError: (err) => {
      toast.error(err.message || "Failed to delete", { id: TOAST_ID });
    },
  });

  return { createRow, updateRow, deleteRow };
}

// Fields that are either generated by the backend, derived from client records,
// or expose row identity — none of these should ever be sent back on create.
// NOTE: `campaignCredentialId` is intentionally NOT stripped — it is a real FK
// column on the client-anchored trackers and must be persisted so the log can be
// linked back to its campaign credential on refresh.
const SYNTHETIC_FIELDS = new Set([
  "id",
  "logId",
  "hasLog",
  "plan",
  "flightStatus",
  "seekEmail",
  "country",
  "submissions",
  "age",
  "createdAt",
  "updatedAt",
  "isDeleted",
  "createdBy",
  "updatedBy",
  "deletedBy",
  "deletedAt",
]);

function stripSynthetic(row: Record<string, any>): Record<string, any> {
  const out: Record<string, any> = {};
  for (const [key, value] of Object.entries(row)) {
    if (SYNTHETIC_FIELDS.has(key)) continue;
    out[key] = value;
  }
  return out;
}

/**
 * Shared create/update/delete semantics for every CEC tracker.
 *
 * A row without a saved log (`hasLog === false`) is created on the first field
 * change and the returned id is adopted, so subsequent changes update it. The
 * decision is keyed off `hasLog`/`logId` — never off id prefixes — which is the
 * bug that previously produced "… not found" on the first edit of a client row.
 */
export function useCecRowEditor<T extends Record<string, any>>(apiBase: string, queryKey: string) {
  const { createRow, updateRow, deleteRow } = useCecMutations(apiBase, queryKey);
  const createInFlight = useRef<Promise<string | null> | null>(null);

  const ensureCreated = async (row: T): Promise<{ id: string | null; created: boolean }> => {
    if (createInFlight.current) {
      const id = await createInFlight.current;
      return { id, created: false };
    }
    const payload = stripSynthetic(row);
    const promise = createRow
      .mutateAsync(payload)
      .then((res) => ((res?.data?.id as string) ?? null))
      .finally(() => {
        createInFlight.current = null;
      });
    createInFlight.current = promise;
    const id = await promise;
    return { id, created: true };
  };

  /**
   * Persist a batch of field changes in a single write. The row is created on
   * the first save (when no log exists yet) and the generated id is adopted;
   * later saves update it. One network write per Done click.
   */
  const saveChanges = async (
    row: T,
    changes: Record<string, any>,
    onSaved?: (merged: T) => void,
  ): Promise<void> => {
    if (Object.keys(changes).length === 0) return;

    if (row.hasLog) {
      await updateRow.mutateAsync({ id: row.logId || row.id, fields: changes });
      onSaved?.({ ...row, ...changes } as T);
      return;
    }

    const { id, created } = await ensureCreated({ ...row, ...changes } as T);
    if (!id) return;

    // A create was already in flight for this row — push the remaining changes
    // as an update rather than dropping them.
    if (!created) {
      await updateRow.mutateAsync({ id, fields: changes });
    }

    onSaved?.({ ...row, ...changes, id, logId: id, hasLog: true } as T);
  };

  const removeRow = (row: T) => deleteRow.mutateAsync({ id: row.logId || row.id });

  return { saveChanges, removeRow };
}
