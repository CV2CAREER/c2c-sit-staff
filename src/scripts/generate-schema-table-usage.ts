import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "fs";
import path from "path";

// Scans the staff backend and the customer backend (they share one database)
// for every table the application actually touches, and writes
// src/config/schema-table-usage.generated.ts. Admin > Database Evaluation uses it
// to tell migrated/legacy tables (present in UAT/PROD, used by nothing) apart
// from real ones.
//
//   npm run schema-usage:scan
//   npm run schema-usage:scan -- --customer=../path/to/c2c-customer-backend/src
//
// Signals, per file under each src/ (scripts/ folders are skipped — one-off
// maintenance scripts reference legacy tables on purpose):
//   * model files:  tableName: "x"
//   * raw SQL:      FROM / JOIN / INTO / UPDATE / TABLE  x   (SQL keywords in
//                   upper case, or any case when the name is quoted, so log
//                   text like "fetch referrals from ..." is not counted)
//   * queryInterface calls: addColumn("x", ...), describeTable("x"), ...
// Over-counting is the safe direction: a falsely "used" table is merely shown
// in the compare; a falsely "unused" one would be hidden.

const ROOT = path.resolve(__dirname, "../..");
const argv = process.argv.slice(2);
const flag = (name: string) => argv.find((a) => a.startsWith(`--${name}=`))?.split("=").slice(1).join("=");

const SOURCES: { name: string; dir: string }[] = [
  { name: "staff", dir: path.join(ROOT, "src") },
  {
    name: "customer",
    dir: path.resolve(ROOT, flag("customer") || "../../C2C Frontend/c2c-customer-backend/src"),
  },
];

const OUTPUT = path.join(ROOT, "src/config/schema-table-usage.generated.ts");

const IDENT = `([A-Za-z_][A-Za-z0-9_]*)`;
const MODEL_TABLE_RE = new RegExp(`tableName\\s*:\\s*['"\`]${IDENT}['"\`]`, "g");
const SQL_UPPER_RE = new RegExp(
  `\\b(?:FROM|JOIN|INTO|UPDATE|TABLE(?:\\s+IF\\s+(?:NOT\\s+)?EXISTS)?)\\s+(?:ONLY\\s+)?(?:"?public"?\\.)?"?${IDENT}"?`,
  "g",
);
const SQL_QUOTED_RE = new RegExp(
  `\\b(?:from|join|into|update|table)\\s+(?:"?public"?\\.)?"${IDENT}"`,
  "gi",
);
const QI_RE = new RegExp(
  `\\b(?:addColumn|removeColumn|changeColumn|renameColumn|describeTable|bulkInsert|bulkUpdate|bulkDelete|addIndex|removeIndex|addConstraint|createTable|dropTable)\\(\\s*['"\`]${IDENT}['"\`]`,
  "g",
);

// SQL keywords that the upper-case pattern would otherwise read as names.
const NOT_TABLES = new Set(["select", "set", "values", "where", "lateral", "unnest", "jsonb_array_elements", "generate_series", "only"]);

const walk = (dir: string, out: string[] = []) => {
  for (const entry of readdirSync(dir)) {
    if (entry === "node_modules" || entry === "scripts" || entry.startsWith(".")) continue;
    const full = path.join(dir, entry);
    const st = statSync(full);
    if (st.isDirectory()) walk(full, out);
    else if (/\.(ts|js)$/.test(entry) && !entry.endsWith(".d.ts") && full !== OUTPUT) out.push(full);
  }
  return out;
};

const usage = new Map<string, Set<string>>();
const note = (table: string, tag: string) => {
  const key = table.toLowerCase();
  if (NOT_TABLES.has(key)) return;
  if (!usage.has(key)) usage.set(key, new Set());
  usage.get(key)!.add(tag);
};

const scanned: string[] = [];
for (const source of SOURCES) {
  if (!existsSync(source.dir)) {
    console.warn(`⚠️  ${source.name}: ${source.dir} not found — skipped. Pass --${source.name}=<path to its src> to include it.`);
    continue;
  }
  const files = walk(source.dir);
  scanned.push(`${source.name} (${files.length} files)`);
  for (const file of files) {
    const text = readFileSync(file, "utf8");
    const isModel = /[\\/]models[\\/]/.test(file);
    for (const m of text.matchAll(MODEL_TABLE_RE)) note(m[1], `${source.name}:model`);
    if (isModel) continue;
    for (const m of text.matchAll(SQL_UPPER_RE)) note(m[1], `${source.name}:sql`);
    for (const m of text.matchAll(SQL_QUOTED_RE)) note(m[1], `${source.name}:sql`);
    for (const m of text.matchAll(QI_RE)) note(m[1], `${source.name}:migration`);
  }
}

const sorted = [...usage.entries()].sort(([a], [b]) => a.localeCompare(b));
const body = sorted.map(([table, tags]) => `  ${JSON.stringify(table)}: ${JSON.stringify([...tags].sort())},`).join("\n");

writeFileSync(
  OUTPUT,
  `// GENERATED by src/scripts/generate-schema-table-usage.ts — do not edit by hand.
// Re-run \`npm run schema-usage:scan\` after adding models or raw SQL in
// either backend. Scanned: ${scanned.join(", ")}.

export const SCHEMA_TABLE_USAGE_GENERATED_AT = ${JSON.stringify(new Date().toISOString())};

export const SCHEMA_TABLE_USAGE: Record<string, string[]> = {
${body}
};
`,
);

console.log(`✅ ${usage.size} referenced table names written to ${path.relative(ROOT, OUTPUT)} (${scanned.join(", ")})`);
